// Keep short prepositions and conjunctions off line ends, as Russian typesetting expects
for (const key in I18N_RU) {
  I18N_RU[key] = I18N_RU[key].replace(/(?<=^|[\s(«\u00A0;])([а-яё]{1,2}) /gi, '$1\u00A0');
}

const I18N_ATTRS = ['alt', 'placeholder', 'aria-label', 'content'];
const i18nEnglish = new Map();

function currentLang() {
  return document.documentElement.lang === 'ru' ? 'ru' : 'en';
}

// Translated string for script-generated text; English is passed in as the fallback
function t(key, english) {
  return currentLang() === 'ru' && key in I18N_RU ? I18N_RU[key] : english;
}

function applyLang(lang) {
  document.documentElement.lang = lang;
  setLangSources(lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    if (!i18nEnglish.has(el)) i18nEnglish.set(el, {});
    const saved = i18nEnglish.get(el);
    if (!('html' in saved)) saved.html = el.innerHTML;
    el.innerHTML = t(el.dataset.i18n, saved.html);
  });

  for (const attr of I18N_ATTRS) {
    document.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => {
      if (!i18nEnglish.has(el)) i18nEnglish.set(el, {});
      const saved = i18nEnglish.get(el);
      if (!(attr in saved)) saved[attr] = el.getAttribute(attr);
      el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`), saved[attr]));
    });
  }

  document.querySelectorAll('[data-set-lang]').forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.dataset.setLang === lang));
  });

  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}

document.querySelectorAll('[data-set-lang]').forEach((btn) => {
  btn.addEventListener('click', () => {
    const lang = btn.dataset.setLang;
    if (lang === currentLang()) return;
    try { localStorage.setItem('lang', lang); } catch {}
    // Drop a ?lang= from a shared link so it doesn't override the choice on reload
    const url = new URL(location.href);
    if (url.searchParams.has('lang')) {
      url.searchParams.delete('lang');
      history.replaceState(null, '', url);
    }
    applyLang(lang);
  });
});

applyLang(currentLang());
